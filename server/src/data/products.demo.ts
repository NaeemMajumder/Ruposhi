const sizesFor = (cat: CategorySlug) => (cat === 'saree' ? SIZES.saree : cat === 'panjabi' ? SIZES.panjabi : SIZES.women);

/** Demo product video (YouTube) — replace per product from Admin → Products → YouTube video link. */
export const DEMO_VIDEO_URL = 'https://www.youtube.com/watch?v=jDecHnDQ1IQ';

export const buildDemoProducts = (now = new Date()): Product[] =>
  DEFS.map((d, i) => {
    const sizes = sizesFor(d.category);
    const variants: Variant[] = [];
    let k = 0;
    d.colors.forEach((col, ci) =>
      sizes.forEach((size) => {
        variants.push({
          sku: `${d.sku}-${ci + 1}${size.replace(/\s+/g, '').toUpperCase().slice(0, 4)}`,
          color: col.name.en,
          size,
          stock: d.stock[k % d.stock.length],
        });
        k++;
      }),
    );
    const images = d.images.map((im) => {
      const [idNum, ext] = Array.isArray(im) ? im : ([im, 'jpeg'] as const);
      return { url: px(idNum, ext), alt: d.imageAlt };
    });
    const created = new Date(now.getTime() - (DEFS.length - i) * 4 * 86400000 - (d.isNew ? -60 * 86400000 : 0));
    return {
      _id: `prd_${String(i + 1).padStart(3, '0')}`,
      slug: d.slug,
      sku: d.sku,
      name: d.name,
      shortDescription: d.short,
      description: d.description,
      category: d.category,
      gender: d.category === 'panjabi' ? 'men' : 'women',
      fabric: d.fabric,
      occasions: d.occasions,
      colors: d.colors,
      sizes,
      variants,
      price: d.price,
      compareAtPrice: d.compareAtPrice,
      costPrice: d.costPrice,
      images,
      videoUrl: DEMO_VIDEO_URL,
      tags: d.tags,
      badges: d.badges ?? [],
      isFeatured: !!d.featured,
      isNewArrival: !!d.isNew,
      preOrder: !!d.preOrder,
      status: 'active',
      rating: d.rating,
      reviewCount: d.reviewCount,
      soldCount: d.soldCount,
      viewCount: d.soldCount * 23 + 140,
      care: CARE[d.care],
      seo: {
        title: `${d.name.en} | Ruposhi`,
        description: d.short.en.slice(0, 155),
      },
      completeTheLook: d.completeTheLook ?? [],
      createdAt: created.toISOString(),
      updatedAt: created.toISOString(),
    } satisfies Product;
  });
